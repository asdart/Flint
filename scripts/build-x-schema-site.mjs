// Generates the Webflow values of the page-level JSON-LD from src/content/schema.ts (single source):
//   docs/webflow/custom-code/x-schema-site.html      site head code (exception x-schema-site, seo.md S-06)
//   docs/webflow/custom-code/blog-index-jsonld.json  the /blog page's jsonLdSchema setting (S-09)
// Usage: node scripts/build-x-schema-site.mjs [--check]   (--check fails if a file is out of date)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { build } from "vite";

const { output } = (
  await build({
    configFile: false,
    logLevel: "silent",
    build: {
      write: false,
      minify: false,
      target: "es2022",
      lib: { entry: "src/content/schema.ts", formats: ["es"], fileName: "schema" },
    },
  })
)[0];
const mod = await import(`data:text/javascript;base64,${Buffer.from(output[0].code).toString("base64")}`);

const siteJson = JSON.stringify(mod.siteSchema());
const files = {
  "docs/webflow/custom-code/x-schema-site.html": `<!-- x-schema-site: Organization + WebSite JSON-LD, every page. Site head custom code, appended after the <style> block of site-head.html (set_site_freeform_code replaces the whole head code: send both). GENERATED by scripts/build-x-schema-site.mjs from src/content/schema.ts: never edit by hand. The pasted source is the <script> block only. -->\n<script type="application/ld+json">${siteJson}</script>\n`,
  "docs/webflow/custom-code/blog-index-jsonld.json": JSON.stringify(mod.blogIndexSchema(), null, 2) + "\n",
};

let stale = false;
for (const [path, text] of Object.entries(files)) {
  if (process.argv.includes("--check")) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== text) {
      console.error(`${path} out of date: run node scripts/build-x-schema-site.mjs`);
      stale = true;
    }
  } else writeFileSync(path, text);
}
if (stale) process.exit(1);
console.log(`site script ${siteJson.length} characters (${process.argv.includes("--check") ? "up to date" : "written"})`);
