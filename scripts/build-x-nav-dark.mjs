// Builds the shipped x-nav-dark head CSS (exception x-nav-dark, docs/webflow/interactions.md) from its single
// source, src/styles/exceptions/x-nav-dark.css: strips comments, minifies, renames `var(--x)` to
// `var(--_flint---x)` (Webflow's published variable names) and swaps the repo's `.fk-nav.is-dark` for the attribute
// Webflow publishes on the root of a `Global / Nav` Dark instance, `.fk-nav[data-wf--nav--variant="dark"]`. A variant
// with no style overrides gets no `w-variant-<id>` class (checked on staging 2026-10-02), so the attribute is the hook.
// Output: docs/webflow/custom-code/x-nav-dark-head.html (Facility partners page head code).
// Usage: node scripts/build-x-nav-dark.mjs [--check]   (--check fails if the file is out of date)
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const CSS_SRC = "src/styles/exceptions/x-nav-dark.css";
const OUT = "docs/webflow/custom-code/x-nav-dark-head.html";

const DARK = `.fk-nav[data-wf--nav--variant="dark"]`;

const css = readFileSync(CSS_SRC, "utf8")
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replaceAll(".fk-nav.is-dark", DARK)
  .replace(/var\(--([\w-]+)\)/g, "var(--_flint---$1)")
  .replace(/\s+/g, " ")
  .replace(/\s*([{}:;,>])\s*/g, "$1")
  .replace(/;}/g, "}")
  .trim();

const html = `<!-- x-nav-dark: the Global / Nav Dark look over the Facility partners hero (white wordmark, links, menu icon, glass Apply button while the bar is at rest). Page HEAD custom code of the Facility partners page, see docs/webflow/interactions.md. GENERATED by scripts/build-x-nav-dark.mjs from ${CSS_SRC} (.fk-nav.is-dark becomes .fk-nav[data-wf--nav--variant="dark"]): never edit by hand. -->
<style>${css}</style>
`;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== html) {
    console.error(`${OUT} out of date: run node scripts/build-x-nav-dark.mjs`);
    process.exit(1);
  }
  console.log(`up to date (style ${css.length} characters)`);
} else {
  writeFileSync(OUT, html);
  console.log(`style ${css.length} characters`);
}
