// Builds the shipped x-illustrations script (exception x-illustrations, docs/webflow/interactions.md) from its
// single source, src/ix/xIllustrations.ts: bundles it, minifies it, and points the `motion` import at the
// CDN. Output: docs/webflow/custom-code/x-illustrations.html, pasted as page footer custom code.
// Usage: node scripts/build-x-illustrations.mjs [--check]   (--check fails if the file is out of date)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { build } from "vite";

const MOTION_URL = "https://cdn.jsdelivr.net/npm/motion@13.4.6/+esm";
const OUT = "docs/webflow/custom-code/x-illustrations.html";
const HEAD_OUT = "docs/webflow/custom-code/x-illustrations-head.html";
const CSS_SRC = "src/styles/exceptions/x-illustrations.css";

const { output } = (
  await build({
    configFile: false,
    logLevel: "silent",
    plugins: [
      {
        name: "motion-from-cdn",
        enforce: "pre",
        resolveId: (id) => (id === "motion" ? { id: MOTION_URL, external: true } : null),
      },
    ],
    build: {
      write: false,
      minify: true,
      target: "es2022",
      lib: { entry: "scripts/x-illustrations-entry.ts", formats: ["es"], fileName: "x-illustrations" },
      // Vite keeps whitespace in ES library output; Rolldown's own minifier strips it.
      rolldownOptions: { output: { minify: { compress: true, mangle: true, codegen: { removeWhitespace: true } } } },
    },
  })
)[0];

const code = output[0].code.trim();
const html = `<!-- x-illustrations: the animated illustrations (Candidates: hero orbit and How It Works rows; later Facility partners). Page footer custom code on the pages that use it, see docs/webflow/interactions.md. GENERATED by scripts/build-x-illustrations.mjs from src/ix/xIllustrations.ts: never edit by hand. Motion ${MOTION_URL.match(/motion@([\d.]+)/)[1]} is an ES module from jsDelivr, deferred by type="module". The pasted source is the <script> block only. -->
<script type="module">${code}</script>
`;

/* The CSS part (the conic mask and the orbit's first paint): minified, tokens renamed for the Webflow variables. */
const css = readFileSync(CSS_SRC, "utf8")
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/var\(--([\w-]+)\)/g, "var(--_flint---$1)")
  .replace(/\s+/g, " ")
  .replace(/\s*([{}:;,>])\s*/g, "$1")
  .replace(/;}/g, "}")
  .replace(/\(([\w-]+):/g, "($1:")
  .trim();
const headHtml = `<!-- x-illustrations (CSS part): the Row 4 progress ring's conic mask and the hero orbit's first paint. Page HEAD custom code of Candidates, see docs/webflow/interactions.md. GENERATED by scripts/build-x-illustrations.mjs from ${CSS_SRC}: never edit by hand. -->
<style>${css}</style>
`;

const files = [
  [OUT, html],
  [HEAD_OUT, headHtml],
];
if (process.argv.includes("--check")) {
  const stale = files.filter(([path, content]) => !existsSync(path) || readFileSync(path, "utf8") !== content);
  if (stale.length) {
    console.error(`${stale.map(([path]) => path).join(", ")} out of date: run node scripts/build-x-illustrations.mjs`);
    process.exit(1);
  }
  console.log(`up to date (script ${code.length} characters, head style ${css.length})`);
} else {
  files.forEach(([path, content]) => writeFileSync(path, content));
  console.log(`script ${code.length} characters, head style ${css.length}`);
}
