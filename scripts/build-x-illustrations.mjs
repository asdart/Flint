// Builds the shipped illustration scripts from their sources, one per page so each page loads only its own code:
//   x-illustrations           (Candidates)        src/ix/xIllustrations.ts         + head CSS
//   x-facility-illustrations  (Facility partners) src/ix/xFacilityIllustrations.ts (no head CSS)
// Both share src/ix/illustrationCore.ts at the source level; each bundle is tree-shaken to its own makers.
// Bundles, minifies and points the `motion` import at the CDN. Output: docs/webflow/custom-code/<name>.html,
// pasted as page footer custom code (see docs/webflow/interactions.md).
// Usage: node scripts/build-x-illustrations.mjs [--check]   (--check fails if a file is out of date)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { build } from "vite";

const MOTION_URL = "https://cdn.jsdelivr.net/npm/motion@13.4.6/+esm";
const MOTION_VERSION = MOTION_URL.match(/motion@([\d.]+)/)[1];
const OUT_DIR = "docs/webflow/custom-code";
const CSS_SRC = "src/styles/exceptions/x-illustrations.css";

async function bundle(entry, fileName) {
  const { output } = (
    await build({
      configFile: false,
      logLevel: "silent",
      plugins: [
        {
          name: "motion-from-cdn",
          enforce: "pre",
          resolveId: (id) => (id === "motion" ? { id: MOTION_URL, external: true } : null),
        },
      ],
      build: {
        write: false,
        minify: true,
        target: "es2022",
        lib: { entry, formats: ["es"], fileName },
        // Vite keeps whitespace in ES library output; Rolldown's own minifier strips it.
        rolldownOptions: { output: { minify: { compress: true, mangle: true, codegen: { removeWhitespace: true } } } },
      },
    })
  )[0];
  return output[0].code.trim();
}

const code = await bundle("scripts/x-illustrations-entry.ts", "x-illustrations");
const html = `<!-- x-illustrations: the animated illustrations of Candidates (hero orbit and How It Works rows). Page footer custom code on Candidates, see docs/webflow/interactions.md. GENERATED by scripts/build-x-illustrations.mjs from src/ix/xIllustrations.ts (+ illustrationCore.ts): never edit by hand. Motion ${MOTION_VERSION} is an ES module from jsDelivr, deferred by type="module". The pasted source is the <script> block only. -->
<script type="module">${code}</script>
`;

const facilityCode = await bundle("scripts/x-facility-illustrations-entry.ts", "x-facility-illustrations");
const facilityHtml = `<!-- x-facility-illustrations: the animated illustrations of Facility partners (network, savings, retention). Page footer custom code on Facility partners only, see docs/webflow/interactions.md. No head CSS. GENERATED by scripts/build-x-illustrations.mjs from src/ix/xFacilityIllustrations.ts (+ illustrationCore.ts): never edit by hand. Motion ${MOTION_VERSION} is an ES module from jsDelivr, deferred by type="module". The pasted source is the <script> block only. -->
<script type="module">${facilityCode}</script>
`;

/* The CSS part (the conic mask and the orbit's first paint): minified, tokens renamed for the Webflow variables. */
const css = readFileSync(CSS_SRC, "utf8")
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/var\(--([\w-]+)\)/g, "var(--_flint---$1)")
  .replace(/\s+/g, " ")
  .replace(/\s*([{}:;,>])\s*/g, "$1")
  .replace(/;}/g, "}")
  .replace(/\(([\w-]+):/g, "($1:")
  .trim();
const headHtml = `<!-- x-illustrations (CSS part): the Row 4 progress ring's conic mask and the hero orbit's first paint. Page HEAD custom code of Candidates, see docs/webflow/interactions.md. GENERATED by scripts/build-x-illustrations.mjs from ${CSS_SRC}: never edit by hand. -->
<style>${css}</style>
`;

const files = [
  [`${OUT_DIR}/x-illustrations.html`, html],
  [`${OUT_DIR}/x-facility-illustrations.html`, facilityHtml],
  [`${OUT_DIR}/x-illustrations-head.html`, headHtml],
];
if (process.argv.includes("--check")) {
  const stale = files.filter(([path, content]) => !existsSync(path) || readFileSync(path, "utf8") !== content);
  if (stale.length) {
    console.error(`${stale.map(([path]) => path).join(", ")} out of date: run node scripts/build-x-illustrations.mjs`);
    process.exit(1);
  }
  console.log(`up to date (x-illustrations ${code.length} characters, head style ${css.length}; x-facility-illustrations ${facilityCode.length})`);
} else {
  files.forEach(([path, content]) => writeFileSync(path, content));
  console.log(`x-illustrations ${code.length} characters, head style ${css.length}; x-facility-illustrations ${facilityCode.length}`);
}
