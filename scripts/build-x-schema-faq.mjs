// Builds the shipped x-schema-faq script (exception x-schema-faq, docs/webflow/interactions.md) from its
// single source, src/ix/xSchemaFaq.ts: bundles it and minifies it into one classic inline script (no
// dependency). Output: docs/webflow/custom-code/x-schema-faq.html (Posts template footer code).
// Usage: node scripts/build-x-schema-faq.mjs [--check]   (--check fails if the file is out of date)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { build } from "vite";

const OUT = "docs/webflow/custom-code/x-schema-faq.html";

const { output } = (
  await build({
    configFile: false,
    logLevel: "silent",
    build: {
      write: false,
      minify: true,
      target: "es2022",
      lib: { entry: "scripts/x-schema-faq-entry.ts", formats: ["iife"], name: "xSchemaFaq", fileName: "x-schema-faq" },
      // Vite keeps whitespace in library output; Rolldown's own minifier strips it.
      rolldownOptions: { output: { minify: { compress: true, mangle: true, codegen: { removeWhitespace: true } } } },
    },
  })
)[0];

const code = output[0].code.trim();
const html = `<!-- x-schema-faq: FAQPage JSON-LD built at runtime from the FAQ H2/H3 in .fk-article-body. Posts template page, before </body> (footer custom code), see docs/webflow/interactions.md. GENERATED by scripts/build-x-schema-faq.mjs from src/ix/xSchemaFaq.ts: never edit by hand. No dependency. The pasted source is the <script> block only. -->
<script>${code}</script>
`;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== html) {
    console.error(`${OUT} out of date: run node scripts/build-x-schema-faq.mjs`);
    process.exit(1);
  }
  console.log(`up to date (script ${code.length} characters)`);
} else {
  writeFileSync(OUT, html);
  console.log(`script ${code.length} characters`);
}
