// Builds the shipped x-video-reduced script (exception x-video-reduced, docs/webflow/interactions.md) from its
// single source, src/ix/videoReduced.ts: bundles it and minifies it into one classic inline script (no
// dependency). Output: docs/webflow/custom-code/x-video-reduced.html (Facility partners page footer code).
// Usage: node scripts/build-x-video-reduced.mjs [--check]   (--check fails if the file is out of date)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { build } from "vite";

const OUT = "docs/webflow/custom-code/x-video-reduced.html";

const { output } = (
  await build({
    configFile: false,
    logLevel: "silent",
    build: {
      write: false,
      minify: true,
      target: "es2022",
      lib: { entry: "scripts/x-video-reduced-entry.ts", formats: ["iife"], name: "xVideoReduced", fileName: "x-video-reduced" },
      // Vite keeps whitespace in library output; Rolldown's own minifier strips it.
      rolldownOptions: { output: { minify: { compress: true, mangle: true, codegen: { removeWhitespace: true } } } },
    },
  })
)[0];

const code = output[0].code.trim();
const html = `<!-- x-video-reduced: pauses a background video marked data-x-video="reduced" (the video itself or a Webflow Background Video wrapper) under prefers-reduced-motion. Page FOOTER custom code of the Facility partners page, see docs/webflow/interactions.md. GENERATED by scripts/build-x-video-reduced.mjs from src/ix/videoReduced.ts: never edit by hand. No dependency. The pasted source is the <script> block only. -->
<script>${code}</script>
`;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== html) {
    console.error(`${OUT} out of date: run node scripts/build-x-video-reduced.mjs`);
    process.exit(1);
  }
  console.log(`up to date (script ${code.length} characters)`);
} else {
  writeFileSync(OUT, html);
  console.log(`script ${code.length} characters`);
}
