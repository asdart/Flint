// Builds the shipped x-carousel script (exception x-carousel, docs/webflow/interactions.md) from its
// single source, src/ix/xCarousel.ts: bundles it with Motion's `JSAnimation` (tree-shaken) into ONE
// self-contained minified module, no CDN request (D-54). Output: docs/webflow/custom-code/x-carousel.html, pasted as page footer custom code.
// Usage: node scripts/build-x-carousel.mjs [--check]   (--check fails if the file is out of date)
import { readFileSync, writeFileSync } from "node:fs";
import { build } from "vite";

const MOTION_VERSION = JSON.parse(readFileSync("node_modules/motion/package.json", "utf8")).version;
const OUT = "docs/webflow/custom-code/x-carousel.html";

const { output } = (
  await build({
    configFile: false,
    logLevel: "silent",
    // Library mode keeps Motion's `process.env.NODE_ENV` checks, which throw in the browser: fix them to production.
    define: { "process.env.NODE_ENV": '"production"' },
    build: {
      write: false,
      minify: true,
      target: "es2022",
      lib: { entry: "scripts/x-carousel-entry.ts", formats: ["es"], fileName: "x-carousel" },
      // Vite keeps whitespace in ES library output; Rolldown's own minifier strips it.
      rolldownOptions: { output: { minify: { compress: true, mangle: true, codegen: { removeWhitespace: true } } } },
    },
  })
)[0];

const code = output[0].code.trim();
const html = `<!-- x-carousel: the shared carousel (Home: How It Works, Testimonials; later Candidates and Facility partners). Page footer custom code on the pages that use it, see docs/webflow/interactions.md. GENERATED by scripts/build-x-carousel.mjs from src/ix/xCarousel.ts: never edit by hand. Motion ${MOTION_VERSION} (JSAnimation only, tree-shaken) is bundled in: one self-contained module, no external request, deferred by type="module". The pasted source is the <script> block only. -->
<script type="module">${code}</script>
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== html) {
    console.error(`${OUT} is out of date: run node scripts/build-x-carousel.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${code.length} characters)`);
} else {
  writeFileSync(OUT, html);
  console.log(`${OUT}: ${code.length} characters`);
}
